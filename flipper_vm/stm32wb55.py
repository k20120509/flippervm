"""STM32WB55 内存映射与外设地址定义.

参考:
  - RM0434 Reference manual STM32WB55
  - Flipper Zero 原理图(显示 ST7567 / 按键 GPIO 映射)
"""

# ===== 主存储区 =====
FLASH_BASE = 0x08000000
FLASH_SIZE = 0x00100000  # 1 MB(STM32WB55VG)

SRAM1_BASE = 0x20000000
SRAM1_SIZE = 0x00030000  # 192 KB

SRAM2_BASE = 0x20030000  # SRAM2a + 2b
SRAM2_SIZE = 0x00010000  # 64 KB

SYSTEM_MEM_BASE = 0x1FFF0000
SYSTEM_MEM_SIZE = 0x00007000

# Cortex-M 系统外设
PPB_BASE = 0xE0000000
SCB_BASE = 0xE000ED00
NVIC_BASE = 0xE000E100
SYSTICK_BASE = 0xE000E010
SCB_VTOR = SCB_BASE + 0x08
SCB_CCR = SCB_BASE + 0x14
SCB_SHPR = SCB_BASE + 0x18

# ===== AHB1 / AHB2 / AHB3 外设 =====
PERIPH_BASE = 0x40000000

# APB1
TIM2_BASE = 0x40000000
PWR_BASE = 0x40007000
I2C1_BASE = 0x40005400
USART2_BASE = 0x40004400
SPI2_BASE = 0x40003800
LPUART1_BASE = 0x40004800   # Low-power UART
LPTIM1_BASE = 0x40007C00    # Low-power Timer 1
LPTIM2_BASE = 0x40009400    # Low-power Timer 2

# APB2
SYSCFG_BASE = 0x40010000    # System Configuration Controller
COMP_BASE = 0x40010200      # Comparators
EXTI_BASE = 0x40010400
TIM1_BASE = 0x40012C00      # Advanced Timer
USART1_BASE = 0x40013800
TIM16_BASE = 0x40014400     # General Timer 16
TIM17_BASE = 0x40014800     # General Timer 17

# AHB1
DMA1_BASE = 0x40020000
DMAMUX1_BASE = 0x40020800
CRC_BASE = 0x40023000
TSC_BASE = 0x40024000       # Touch Sensing Controller

# AHB2
GPIOA_BASE = 0x48000000
GPIOB_BASE = 0x48000400
GPIOC_BASE = 0x48000800
GPIOD_BASE = 0x48000C00
GPIOH_BASE = 0x48001C00
ADC_BASE = 0x50040000

# AHB3
RCC_BASE       = 0x58000000
IPCC_BASE      = 0x58000C00  # CPU1 <-> CPU2 通信控制器
FLASH_REG_BASE = 0x58004000  # FLASH 控制寄存器
RNG_BASE       = 0x58001000  # 真随机数发生器
AES1_BASE      = 0x58001100
AES2_BASE      = 0x58001200
HWSEM_BASE     = 0x58001400  # 硬件信号量 (32 个)
PKA_BASE       = 0x58002000  # 公钥加速器
SAES_BASE      = 0x58002800
VREFBUF_BASE   = 0x58003000  # Voltage Reference Buffer
# RTC 使用独立地址(真实 0x58004000 与 FLASH_REG 复用空间,这里偏移到安全位置,防止地址冲突)
RTC_BASE       = 0x58005000
# PWR 在 APB1 = 0x40007000, PWR_CR4.C2BOOT 位控制 CPU2 启动

# ===== Flipper Zero 按键 → GPIO 映射 =====
# 与 furi_hal_resources 中的 BUTTON_* 引脚一致
BUTTON_MAP = {
    "back":  (GPIOC_BASE, 1 << 0),   # PC0
    "down":  (GPIOC_BASE, 1 << 1),   # PC1
    "up":    (GPIOC_BASE, 1 << 2),   # PC2
    "right": (GPIOC_BASE, 1 << 3),   # PC3
    "left":  (GPIOB_BASE, 1 << 4),   # PB4
    "ok":    (GPIOB_BASE, 1 << 5),   # PB5
}

# ST7567 显示屏:128x64 单色 OLED,通过 SPI2 + DC(PB11)+ RST(PC9)
DISPLAY_WIDTH = 128
DISPLAY_HEIGHT = 64
